//! ZWM1 world ownership metadata.
//!
//! A world belongs to exactly one profile. The runtime must compare
//! `profile_id` against the selected profile before serving chunks; importing
//! is the only offline crossing point and writes a new target-owned world.
//!
//! Storage: one LSM row in the reserved world-metadata dimension. The
//! permissions matrix already owns `(254, 0, 0)`, so ZWM1 uses the next row,
//! `(254, 0, 1)`. The value is a compact, versioned binary record:
//!
//!   magic "ZWM1" | schema_version u8
//!   profile_id           u8 length + bytes
//!   created_by_mc        u8 length + bytes
//!   protocol             i32 BE
//!   worldgen_profile     u8 length + bytes
//!   source_worldgen      u8 length + bytes (empty for native worlds)
//!   block_registry_version u32 BE
//!   min_y                i16 BE
//!   max_y                i16 BE
//!   section_count        u16 BE
//!
//! `decode` returns slices borrowed from its input. Keep the row bytes alive
//! while using the result, or copy the fields if they must outlive it.
//!
//! Missing metadata is a legacy world (1.7 / ZC1) and only the `mc5` profile
//! may open it directly. That policy belongs at the startup boundary; this
//! module provides the encoding, validation, and ownership checks only.

const std = @import("std");
const store_mod = @import("store.zig");

pub const magic = "ZWM1";
pub const schema_version: u8 = 1;
pub const dim: u8 = 254;
/// Permissions uses `(254, 0, 0)`; keep metadata on the next row.
pub const key = store_mod.encodeKey(dim, 0, 1);
pub const max_field_len: usize = 64;

pub const Meta = struct {
    profile_id: []const u8,
    created_by_mc: []const u8,
    protocol: i32,
    worldgen_profile: []const u8,
    /// Empty for worlds generated by this profile; set by an importer when the
    /// source and target generators differ.
    source_worldgen: []const u8 = "",
    block_registry_version: u32 = 1,
    min_y: i16 = 0,
    max_y: i16 = 255,
    section_count: u16 = 16,
};

pub const ValidationError = error{InvalidMeta};
pub const DecodeError = error{
    BadMagic,
    UnsupportedSchema,
    Truncated,
    InvalidMeta,
    TrailingBytes,
};
pub const OwnershipError = error{ ForeignProfile, ForeignWorldgen };

/// Validate both the field limits and the chunk geometry owned by the record.
/// Geometry is kept here so a corrupted row cannot make a later chunk reader
/// index outside the profile's height bounds.
pub fn validate(meta: Meta) ValidationError!void {
    if (meta.profile_id.len == 0 or meta.profile_id.len > max_field_len) return error.InvalidMeta;
    if (meta.created_by_mc.len == 0 or meta.created_by_mc.len > max_field_len) return error.InvalidMeta;
    if (meta.worldgen_profile.len == 0 or meta.worldgen_profile.len > max_field_len) return error.InvalidMeta;
    if (meta.source_worldgen.len > max_field_len) return error.InvalidMeta;
    if (meta.protocol <= 0) return error.InvalidMeta;
    if (meta.section_count == 0) return error.InvalidMeta;
    if (meta.min_y > meta.max_y) return error.InvalidMeta;
    if (@mod(meta.min_y, 16) != 0) return error.InvalidMeta;

    const height = @as(i32, meta.max_y) - @as(i32, meta.min_y) + 1;
    const covered = @as(i32, meta.section_count) * 16;
    if (height != covered) return error.InvalidMeta;
}

/// Encode a metadata row. The caller owns the returned allocation.
pub fn encode(alloc: std.mem.Allocator, meta: Meta) ![]u8 {
    try validate(meta);

    const n = 4 + 1 +
        1 + meta.profile_id.len +
        1 + meta.created_by_mc.len +
        4 +
        1 + meta.worldgen_profile.len +
        1 + meta.source_worldgen.len +
        4 + 2 + 2 + 2;
    const out = try alloc.alloc(u8, n);
    errdefer alloc.free(out);

    var i: usize = 0;
    @memcpy(out[i..][0..magic.len], magic);
    i += magic.len;
    out[i] = schema_version;
    i += 1;
    putString(out, &i, meta.profile_id);
    putString(out, &i, meta.created_by_mc);
    std.mem.writeInt(i32, out[i..][0..4], meta.protocol, .big);
    i += 4;
    putString(out, &i, meta.worldgen_profile);
    putString(out, &i, meta.source_worldgen);
    std.mem.writeInt(u32, out[i..][0..4], meta.block_registry_version, .big);
    i += 4;
    std.mem.writeInt(i16, out[i..][0..2], meta.min_y, .big);
    i += 2;
    std.mem.writeInt(i16, out[i..][0..2], meta.max_y, .big);
    i += 2;
    std.mem.writeInt(u16, out[i..][0..2], meta.section_count, .big);
    i += 2;
    std.debug.assert(i == out.len);
    return out;
}

fn putString(out: []u8, i: *usize, s: []const u8) void {
    out[i.*] = @intCast(s.len);
    i.* += 1;
    @memcpy(out[i.*..][0..s.len], s);
    i.* += s.len;
}

/// Decode a metadata row. Strings borrow `bytes`; see the module docs.
pub fn decode(bytes: []const u8) DecodeError!Meta {
    var r = bytes;
    if (!std.mem.eql(u8, try take(&r, magic.len), magic)) return error.BadMagic;
    const schema = (try take(&r, 1))[0];
    if (schema != schema_version) return error.UnsupportedSchema;

    const profile_id = try takeString(&r);
    const created_by_mc = try takeString(&r);
    const protocol = std.mem.readInt(i32, (try take(&r, 4))[0..4], .big);
    const worldgen_profile = try takeString(&r);
    const source_worldgen = try takeString(&r);
    const block_registry_version = std.mem.readInt(u32, (try take(&r, 4))[0..4], .big);
    const min_y = std.mem.readInt(i16, (try take(&r, 2))[0..2], .big);
    const max_y = std.mem.readInt(i16, (try take(&r, 2))[0..2], .big);
    const section_count = std.mem.readInt(u16, (try take(&r, 2))[0..2], .big);
    if (r.len != 0) return error.TrailingBytes;

    const meta = Meta{
        .profile_id = profile_id,
        .created_by_mc = created_by_mc,
        .protocol = protocol,
        .worldgen_profile = worldgen_profile,
        .source_worldgen = source_worldgen,
        .block_registry_version = block_registry_version,
        .min_y = min_y,
        .max_y = max_y,
        .section_count = section_count,
    };
    validate(meta) catch return error.InvalidMeta;
    return meta;
}

fn take(r: *[]const u8, n: usize) DecodeError![]const u8 {
    if (r.*.len < n) return error.Truncated;
    const s = r.*[0..n];
    r.* = r.*[n..];
    return s;
}

fn takeString(r: *[]const u8) DecodeError![]const u8 {
    const len: usize = (try take(r, 1))[0];
    if (len > max_field_len) return error.InvalidMeta;
    return take(r, len);
}

/// Runtime ownership check: a foreign profile is never opened, even when the
/// schema and block registry happen to match.
pub fn ensureProfile(meta: Meta, expected_profile_id: []const u8) error{ForeignProfile}!void {
    if (!std.mem.eql(u8, meta.profile_id, expected_profile_id)) return error.ForeignProfile;
}

/// New chunks must be generated by the profile that owns the world; a
/// different generator is an import operation, not a runtime switch.
pub fn ensureWorldgen(meta: Meta, expected_worldgen_profile: []const u8) error{ForeignWorldgen}!void {
    if (!std.mem.eql(u8, meta.worldgen_profile, expected_worldgen_profile)) return error.ForeignWorldgen;
}

pub fn ensureOwnedBy(
    meta: Meta,
    profile_id: []const u8,
    worldgen_profile: []const u8,
) OwnershipError!void {
    try ensureProfile(meta, profile_id);
    try ensureWorldgen(meta, worldgen_profile);
}

const fixture = Meta{
    .profile_id = "mc5",
    .created_by_mc = "1.7.10",
    .protocol = 5,
    .worldgen_profile = "v5",
    .source_worldgen = "",
    .block_registry_version = 1,
    .min_y = 0,
    .max_y = 255,
    .section_count = 16,
};

const fixture_bytes = [_]u8{
    'Z',  'W',  'M',  '1',  0x01,
    0x03, 'm',  'c',  '5',  0x06,
    '1',  '.',  '7',  '.',  '1',
    '0',  0x00, 0x00, 0x00, 0x05,
    0x02, 'v',  '5',  0x00, 0x00,
    0x00, 0x00, 0x01, 0x00, 0x00,
    0x00, 0xFF, 0x00, 0x10,
};

test "ZWM1 golden encoding and borrowed decode" {
    const enc = try encode(std.testing.allocator, fixture);
    defer std.testing.allocator.free(enc);
    try std.testing.expectEqualSlices(u8, &fixture_bytes, enc);

    const dec = try decode(enc);
    try std.testing.expectEqualStrings("mc5", dec.profile_id);
    try std.testing.expectEqualStrings("1.7.10", dec.created_by_mc);
    try std.testing.expectEqual(@as(i32, 5), dec.protocol);
    try std.testing.expectEqualStrings("v5", dec.worldgen_profile);
    try std.testing.expectEqual(@as(usize, 0), dec.source_worldgen.len);
    try std.testing.expectEqual(@as(u32, 1), dec.block_registry_version);
    try std.testing.expectEqual(@as(i16, 0), dec.min_y);
    try std.testing.expectEqual(@as(i16, 255), dec.max_y);
    try std.testing.expectEqual(@as(u16, 16), dec.section_count);
}

test "ZWM1 source worldgen survives import metadata" {
    const imported = Meta{
        .profile_id = "mc47",
        .created_by_mc = "1.8.9",
        .protocol = 47,
        .worldgen_profile = "v47",
        .source_worldgen = "v5",
        .block_registry_version = 2,
        .min_y = -64,
        .max_y = 319,
        .section_count = 24,
    };
    const enc = try encode(std.testing.allocator, imported);
    defer std.testing.allocator.free(enc);
    const dec = try decode(enc);
    try std.testing.expectEqualStrings("v5", dec.source_worldgen);
    try std.testing.expectEqual(@as(i16, -64), dec.min_y);
    try std.testing.expectEqual(@as(u16, 24), dec.section_count);
}

test "ZWM1 rejects malformed records" {
    const a = std.testing.allocator;
    const enc = try encode(a, fixture);
    defer a.free(enc);

    try std.testing.expectError(error.BadMagic, decode(&[_]u8{ 'X', 'W', 'M', '1', 1 }));
    try std.testing.expectError(error.UnsupportedSchema, decode(&[_]u8{ 'Z', 'W', 'M', '1', 2 }));
    for (0..enc.len) |n| {
        try std.testing.expectError(error.Truncated, decode(enc[0..n]));
    }

    var trailing = try a.alloc(u8, enc.len + 1);
    defer a.free(trailing);
    @memcpy(trailing[0..enc.len], enc);
    trailing[enc.len] = 0;
    try std.testing.expectError(error.TrailingBytes, decode(trailing));

    var bad_geometry = try a.dupe(u8, enc);
    defer a.free(bad_geometry);
    bad_geometry[31] = 0xFE; // max_y 255 -> 254, no longer 16 sections
    try std.testing.expectError(error.InvalidMeta, decode(bad_geometry));

    var bad_protocol = try a.dupe(u8, enc);
    defer a.free(bad_protocol);
    bad_protocol[16] = 0xFF;
    bad_protocol[17] = 0xFF;
    bad_protocol[18] = 0xFF;
    bad_protocol[19] = 0xFF;
    try std.testing.expectError(error.InvalidMeta, decode(bad_protocol));

    var bad_len = try a.dupe(u8, enc);
    defer a.free(bad_len);
    bad_len[5] = @intCast(max_field_len + 1);
    try std.testing.expectError(error.InvalidMeta, decode(bad_len));

    const too_long = "a" ** (max_field_len + 1);
    try std.testing.expectError(error.InvalidMeta, encode(a, .{
        .profile_id = too_long,
        .created_by_mc = "1.7.10",
        .protocol = 5,
        .worldgen_profile = "v5",
    }));
    try std.testing.expectError(error.InvalidMeta, encode(a, .{
        .profile_id = "",
        .created_by_mc = "1.7.10",
        .protocol = 5,
        .worldgen_profile = "v5",
    }));
    try std.testing.expectError(error.InvalidMeta, encode(a, .{
        .profile_id = "mc5",
        .created_by_mc = "",
        .protocol = 5,
        .worldgen_profile = "v5",
    }));
    try std.testing.expectError(error.InvalidMeta, encode(a, .{
        .profile_id = "mc5",
        .created_by_mc = "1.7.10",
        .protocol = 5,
        .worldgen_profile = "",
    }));
    try std.testing.expectError(error.InvalidMeta, encode(a, .{
        .profile_id = "mc5",
        .created_by_mc = "1.7.10",
        .protocol = 5,
        .worldgen_profile = "v5",
        .min_y = 1,
    }));
    try std.testing.expectError(error.InvalidMeta, encode(a, .{
        .profile_id = "mc5",
        .created_by_mc = "1.7.10",
        .protocol = 5,
        .worldgen_profile = "v5",
        .section_count = 8,
    }));
}

test "ZWM1 ownership checks are fail closed" {
    try ensureOwnedBy(fixture, "mc5", "v5");
    try std.testing.expectError(error.ForeignProfile, ensureProfile(fixture, "mc47"));
    try std.testing.expectError(error.ForeignWorldgen, ensureWorldgen(fixture, "v47"));
    try std.testing.expectError(error.ForeignProfile, ensureOwnedBy(fixture, "mc47", "v5"));
}

test "ZWM1 key is reserved and distinct from permissions" {
    const permissions_key = store_mod.encodeKey(dim, 0, 0);
    try std.testing.expectEqual(dim, key[0]);
    try std.testing.expect(!std.mem.eql(u8, key[0..], permissions_key[0..]));
}
