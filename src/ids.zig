
//! Canonical 1.7.10 block + item numeric IDs, machine-extracted from
//! the official 1.7.10 server jar registries (Block `aji.p`, Item `adb`
//! static init: `e.a(ID, "name", ...)`). Single flat `u16` namespace,
//! matching how the code treats them (one `Stack.id`, one block id
//! space on the wire and in chunk storage).
//!
//! 11 names exist as both block and item (bed 26/355, brewing_stand
//! 117/379, cake 92/354, cauldron 118/380, flower_pot 140/390,
//! iron_door 71/330, nether_wart 115/372, reeds 83/338, skull 144/397,
//! wheat 59/296, wooden_door 64/324) and take `_block`/`_item` suffixes;
//! everything else keeps its jar name verbatim.
//! Empty ranges (blocks 165-169, items 409-416/423-2255/2268+) have no
//! constant on purpose: using one would mean inventing an ID.

const std = @import("std");
test "ids anchor values" {
    try std.testing.expectEqual(@as(u16, 1), stone);
    try std.testing.expectEqual(@as(u16, 15), iron_ore);
    try std.testing.expectEqual(@as(u16, 61), furnace);
    try std.testing.expectEqual(@as(u16, 62), lit_furnace);
    try std.testing.expectEqual(@as(u16, 265), iron_ingot);
    try std.testing.expectEqual(@as(u16, 263), coal);
    try std.testing.expectEqual(@as(u16, 280), stick);
    try std.testing.expectEqual(@as(u16, 26), bed_block);
    try std.testing.expectEqual(@as(u16, 355), bed_item);
}

