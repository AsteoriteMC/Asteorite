//! Canonical block/item identity for the whole project.
//!
//! `Id` is an interned handle, NOT a wire value: sequential u16 assigned
//! in declaration order (blocks, then items; append-only, never reorder).
//! Wire encodings live per protocol version (see proto/vX/wire_ids.zig);
//! conversion happens only at boundaries (packet parse/frame, chunk
//! encode/decode, Anvil/player.dat import). Sim, worldgen, and storage
//! all speak canonical ids.
//!
//! Names are the 1.7.10 jar registry names (verified against the official
//! server jar: Block `aji.p` / Item `adb` static init `e.a(ID, "name")`).
//! `_block`/`_item` disambiguate the 11 names shared by both registries.

const std = @import("std");

test "ids anchor values" {
    try std.testing.expectEqual(@as(u16, 0), @intFromEnum(air));
    try std.testing.expectEqual(@as(u16, 1), @intFromEnum(stone));
    try std.testing.expectEqual(@as(u16, 61), @intFromEnum(furnace));
    try std.testing.expectEqual(@as(u16, 62), @intFromEnum(lit_furnace));
    try std.testing.expectEqual(@as(u16, 180), @intFromEnum(iron_ingot));
    try std.testing.expectEqual(@as(u16, 178), @intFromEnum(coal));
    try std.testing.expectEqual(@as(u16, 195), @intFromEnum(stick));
    try std.testing.expectEqual(@as(u16, 26), @intFromEnum(bed_block));
    try std.testing.expectEqual(@as(u16, 270), @intFromEnum(bed_item));
    try std.testing.expectEqual(COUNT, @typeInfo(Id).@"enum".fields.len);
}

